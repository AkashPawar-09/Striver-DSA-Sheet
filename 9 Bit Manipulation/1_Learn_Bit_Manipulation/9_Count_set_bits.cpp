// Question: Count the number of 1s in the binary representation.

#include<bits/stdc++.h>
using namespace std;



class Solution {
public:
    int countSetBits(int n) {
        int count = 0;
        while (n) {                         // loop till n becomes 0 (false)
            count = count + (n & 1);        // increases count if last bit is 1
            n = n >> 1;                     // move all bits to right side (removes last automatically)
        }
        return count;                       // returns count
    }
};



int main() {
    Solution obj;
    int n ;
    cin >> n ;
    cout << obj.countSetBits(n);
    return 0;
}



// Time Complexity: O(log n)
// Space Complexity: O(1)




